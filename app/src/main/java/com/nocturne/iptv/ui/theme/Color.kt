package com.nocturne.iptv.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * Nocturne palette.
 *
 * A single mint of red on near-black. Every colour is named after where it
 * would be found in a haunted house, which keeps intent obvious at call sites.
 */
object NocturnePalette {
    /** Deepest background — the void behind everything. */
    val Abyss = Color(0xFF05030A)

    /** Cards and sheets. */
    val Crypt = Color(0xFF0C0912)

    /** Raised surfaces, dividers. */
    val Coffin = Color(0xFF16121F)

    /** Primary accent — dried blood. */
    val Blood = Color(0xFFB20717)

    /** Highlight accent — fresh blood / embers. */
    val Ember = Color(0xFFFF3B3B)

    /** Bright glow for focus and play states. */
    val Gleam = Color(0xFFFF6B6B)

    /** Primary text — aged bone. */
    val Bone = Color(0xFFE9E2D0)

    /** Muted text and metadata. */
    val Ash = Color(0xFF8A8090)

    /** Success/online indicator. */
    val Mould = Color(0xFF4E7A4E)
}